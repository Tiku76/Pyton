# casting tipe data adalah mengubah tipe data dari satu jenis ke jenis lainnya
# str,int,float,bool
# contoh str > int
# contoh int > float

data_int = 10
data_str = float(data_int)
print(data_str, type(data_int))

data_baru = int(input("masukan umur anda: "))
print(data_baru, type(data_baru))