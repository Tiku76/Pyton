# operasi aritmatika adalah operasi perhitungan angka sederhana
# % -> modulus
# ** -> pangkat
# +,-,*,/,%,**

x = 2
y = 3
z = 5

print(510 % 150)

hasil = x * y + z - y ** z + 100 ** y % y
print(x,'*',y,'+',z,'-',y,'**',z,'+',100,'**',y,'%',y,'=', hasil)

